CREATE TABLE CATEGORIA(
    ID_CATEGORIA SERIAL PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    DESCRIPCION TEXT,
    ID_CATEGORIA_PADRE INT,
