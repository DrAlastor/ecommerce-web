    ESTADO VARCHAR(50) NOT NULL,
    CHECK (LIMITE_USOS IS NULL OR USOS_ACTUALES <= LIMITE_USOS),
    CHECK (TIPO_DESCUENTO <> 'porcentaje' OR VALOR_DESCUENTO <= 100),
    CHECK (FECHA_FIN >= FECHA_INICIO)
