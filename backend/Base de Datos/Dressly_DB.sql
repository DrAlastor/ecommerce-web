CREATE TABLE PROMOCION(
    ID_PROMOCION SERIAL PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    LIMITE_USOS INT CHECK (LIMITE_USOS >= 0),
    USOS_ACTUALES INT NOT NULL CHECK (USOS_ACTUALES >= 0),
    TIPO_DESCUENTO VARCHAR(50) NOT NULL CHECK (TIPO_DESCUENTO IN ('porcentaje', 'monto_fijo')),
    VALOR_DESCUENTO DECIMAL(12,2) NOT NULL CHECK (VALOR_DESCUENTO > 0 AND VALOR_DESCUENTO <> 'NaN'::DECIMAL),
    FECHA_INICIO TIMESTAMPTZ NOT NULL,
