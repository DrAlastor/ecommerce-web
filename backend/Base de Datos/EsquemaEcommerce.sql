-- Función para actualizar automáticamente el timestamp al modificar stock
CREATE OR REPLACE FUNCTION actualizar_timestamp_inventario()
RETURNS TRIGGER AS $$
BEGIN
    NEW.ULTIMA_ACTUALIZACION = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_actualizar_timestamp_inventario ON INVENTARIO_SUCURSAL;
CREATE TRIGGER trg_actualizar_timestamp_inventario
BEFORE UPDATE ON INVENTARIO_SUCURSAL
FOR EACH ROW
EXECUTE FUNCTION actualizar_timestamp_inventario();

