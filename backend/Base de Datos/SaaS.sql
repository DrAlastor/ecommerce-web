CREATE TABLE MONEDA (
ID SERIAL PRIMARY KEY,
CODIGO VARCHAR(3) NOT NULL UNIQUE,
NOMBRE VARCHAR(100) NOT NULL,
SIMBOLO VARCHAR(10),
DECIMALES INTEGER NOT NULL,
ACTIVO BOOLEAN NOT NULL
);

CREATE TABLE PAIS (
ID SERIAL PRIMARY KEY,
CODIGO_ISO2 VARCHAR(2) NOT NULL UNIQUE,
CODIGO_ISO3 VARCHAR(3) NOT NULL UNIQUE,
NOMBRE VARCHAR(150) NOT NULL,
ACTIVO BOOLEAN NOT NULL
);

CREATE TABLE PLANES_SUSCRIPCION (
ID SERIAL PRIMARY KEY,
CODIGO VARCHAR(50) NOT NULL UNIQUE,
NOMBRE VARCHAR(100) NOT NULL,
TIPO_PLAN VARCHAR(50) NOT NULL,
DESCRIPCION TEXT NOT NULL,
PRECIO_MENSUAL NUMERIC(12,2) NOT NULL,
PRECIO_ANUAL NUMERIC(12,2) NOT NULL,
MONEDA VARCHAR(3) NOT NULL,
DURACION_PRUEBA_DIAS INTEGER NOT NULL,
REQUIERE_PAGO BOOLEAN NOT NULL,
LIMITE_USUARIOS INTEGER NOT NULL,
LIMITE_SUCURSALES INTEGER NOT NULL,
LIMITE_ALMACENES INTEGER NOT NULL,
LIMITE_PRODUCTOS INTEGER NOT NULL,
PERMITE_OFFLINE BOOLEAN NOT NULL DEFAULT TRUE,
PERMITE_IA_REPORTES BOOLEAN NOT NULL DEFAULT FALSE,
PERMITE_ML_ANALYTICS BOOLEAN NOT NULL DEFAULT FALSE,
FECHA_CREACION TIMESTAMP NOT NULL,
FECHA_MODIFICACION TIMESTAMP NOT NULL,
ACTIVO BOOLEAN NOT NULL
);

CREATE TABLE MODULOS_SAAS (
ID SERIAL PRIMARY KEY,
CODIGO VARCHAR(50) NOT NULL UNIQUE,
NOMBRE VARCHAR(100) NOT NULL,
DESCRIPCION TEXT NOT NULL,
ORDEN_VISUAL INTEGER NOT NULL,
ACTIVO BOOLEAN NOT NULL,
FECHA_CREACION TIMESTAMP NOT NULL
);

CREATE TABLE FUNCIONES_SAAS (
ID SERIAL PRIMARY KEY,
MODULO_ID INTEGER NOT NULL,
CODIGO VARCHAR(80) NOT NULL UNIQUE,
NOMBRE VARCHAR(150) NOT NULL,
RUTA_FRONTEND VARCHAR(200),
ACTIVO BOOLEAN NOT NULL,
FECHA_CREACION TIMESTAMP NOT NULL,
FOREIGN KEY (MODULO_ID) REFERENCES MODULOS_SAAS(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

CREATE TABLE PLAN_FUNCIONES (
ID SERIAL PRIMARY KEY,
PLAN_ID INTEGER NOT NULL,
FUNCION_ID INTEGER NOT NULL,
HABILITADA BOOLEAN NOT NULL,
FECHA_CREACION TIMESTAMP NOT NULL,
FOREIGN KEY (PLAN_ID) REFERENCES PLANES_SUSCRIPCION(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
FOREIGN KEY (FUNCION_ID) REFERENCES FUNCIONES_SAAS(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
UNIQUE (PLAN_ID,FUNCION_ID)
);

CREATE TABLE EMPRESA (
ID SERIAL PRIMARY KEY,
PAIS_ID INTEGER NOT NULL,
MONEDA_PRINCIPAL_ID INTEGER NOT NULL,
MONEDA_SECUNDARIA_ID INTEGER,
CODIGO_EMPRESA VARCHAR(30) NOT NULL UNIQUE,
RAZON_SOCIAL VARCHAR(200) NOT NULL,
NOMBRE_COMERCIAL VARCHAR(200) NOT NULL,
NIT VARCHAR(50),
DIRECCION VARCHAR(255),
TELEFONO VARCHAR(50),
EMAIL VARCHAR(150) NOT NULL,
CIUDAD_NOMBRE VARCHAR(150) NOT NULL,
ESTADO VARCHAR(30) NOT NULL,
FECHA_CREACION TIMESTAMP NOT NULL,
FECHA_MODIFICACION TIMESTAMP NOT NULL,
FECHA_SUSPENSION TIMESTAMP,
FOREIGN KEY (PAIS_ID) REFERENCES PAIS(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
FOREIGN KEY (MONEDA_PRINCIPAL_ID) REFERENCES MONEDA(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
FOREIGN KEY (MONEDA_SECUNDARIA_ID) REFERENCES MONEDA(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

CREATE TABLE TENANT_DATABASE (
ID SERIAL PRIMARY KEY,
EMPRESA_ID INTEGER NOT NULL UNIQUE,
NOMBRE_DATABASE VARCHAR(150) NOT NULL,
NOMBRE_ESQUEMA VARCHAR(150) NOT NULL UNIQUE,
CLOUD_INSTANCE VARCHAR(150),
HOST VARCHAR(200) NOT NULL,
PORT INTEGER NOT NULL,
SECRET_REFERENCE VARCHAR(250),
CLOUD_PROVIDER VARCHAR(50) DEFAULT 'AZURE',
ESTADO VARCHAR(30) NOT NULL,
VERSION_ESQUEMA VARCHAR(30) NOT NULL,
ULTIMA_MIGRACION TIMESTAMP,
FECHA_CREACION TIMESTAMP NOT NULL,
FECHA_MODIFICACION TIMESTAMP NOT NULL,
FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

CREATE TABLE SUSCRIPCION (
ID SERIAL PRIMARY KEY,
EMPRESA_ID INTEGER NOT NULL,
PLAN_ID INTEGER NOT NULL,
CICLO_FACTURACION VARCHAR(30) NOT NULL,
ESTADO VARCHAR(30) NOT NULL,
ES_PRUEBA BOOLEAN NOT NULL,
AUTO_RENOVACION BOOLEAN NOT NULL,
FECHA_INICIO TIMESTAMP NOT NULL,
FECHA_FIN TIMESTAMP NOT NULL,
FECHA_CANCELACION TIMESTAMP,
MOTIVO_CANCELACION VARCHAR(250),
FECHA_CREACION TIMESTAMP NOT NULL,
FECHA_MODIFICACION TIMESTAMP NOT NULL,
FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
FOREIGN KEY (PLAN_ID) REFERENCES PLANES_SUSCRIPCION(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

CREATE TABLE PAGO (
ID SERIAL PRIMARY KEY,
SUSCRIPCION_ID INTEGER NOT NULL,
METODO_PAGO VARCHAR(50) NOT NULL,
IMPORTE NUMERIC(12,2) NOT NULL,
TRANSACCION_EXTERNA VARCHAR(200),
ESTADO VARCHAR(30) NOT NULL,
FECHA_PAGO TIMESTAMP NOT NULL,
FOREIGN KEY (SUSCRIPCION_ID) REFERENCES SUSCRIPCION(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

CREATE TABLE USUARIO_MASTER (
ID SERIAL PRIMARY KEY,
NOMBRE VARCHAR(100) NOT NULL,
APELLIDO VARCHAR(150) NOT NULL,
EMAIL VARCHAR(150) NOT NULL UNIQUE,
PASSWORD VARCHAR(250) NOT NULL,
ROL_GLOBAL VARCHAR(50) NOT NULL,
FECHA_CREACION TIMESTAMP NOT NULL,
FECHA_MODIFICACION TIMESTAMP NOT NULL,
ACTIVO BOOLEAN NOT NULL
);

CREATE TABLE HISTORIAL_BACKUPS (
ID SERIAL PRIMARY KEY,
EMPRESA_ID INTEGER NOT NULL,
TENANT_DATABASE_ID INTEGER NOT NULL,
NOMBRE_ARCHIVO VARCHAR(250) NOT NULL,
RUTA_STORAGE VARCHAR(500) NOT NULL,
CONTAINER_BLOB VARCHAR(150),
TAMANO_BYTES BIGINT NOT NULL,
ESTADO VARCHAR(30) NOT NULL,
FECHA_CREACION TIMESTAMP NOT NULL,
TIPO_BACKUP VARCHAR(30) DEFAULT 'BAJO_DEMANDA',
SOLICITADO_POR VARCHAR(150),
FECHA_INICIO TIMESTAMP,
FECHA_FIN TIMESTAMP,
CHECKSUM_SHA256 VARCHAR(64),
RETENCION_HASTA TIMESTAMP,
JOB_ID VARCHAR(64),
ESTADO_VERIFICACION VARCHAR(30) DEFAULT 'PENDIENTE',
CODIGO_ERROR TEXT,
FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
FOREIGN KEY (TENANT_DATABASE_ID) REFERENCES TENANT_DATABASE(ID)
    ON UPDATE CASCADE
    ON DELETE CASCADE
);

CREATE TABLE HISTORIAL_RESTAURACIONES (
ID SERIAL PRIMARY KEY,
EMPRESA_ID INTEGER NOT NULL REFERENCES EMPRESA(ID) ON DELETE CASCADE,
BACKUP_ID INTEGER NOT NULL REFERENCES HISTORIAL_BACKUPS(ID) ON DELETE CASCADE,
TIPO_RESTAURACION VARCHAR(30) NOT NULL,
TABLAS_SELECCIONADAS TEXT,
SOLICITADO_POR VARCHAR(150) NOT NULL,
ESTADO VARCHAR(30) NOT NULL,
FECHA_INICIO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
FECHA_FIN TIMESTAMP,
DETALLES TEXT,
REVERSION_DISPONIBLE BOOLEAN DEFAULT TRUE
);

CREATE TABLE POLITICA_BACKUP_TENANT (
EMPRESA_ID INTEGER PRIMARY KEY REFERENCES EMPRESA(ID) ON DELETE CASCADE,
FRECUENCIA VARCHAR(30) NOT NULL DEFAULT 'DIARIO',
HORA_EJECUCION VARCHAR(10) NOT NULL DEFAULT '02:00',
DIAS_RETENCION INTEGER NOT NULL DEFAULT 30,
ACTIVO BOOLEAN NOT NULL DEFAULT TRUE,
NOTIFICAR_EMAIL VARCHAR(150),
ULTIMO_BACKUP_AUTOMATICO TIMESTAMP,
FECHA_MODIFICACION TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE BITACORA_AUDITORIA (
