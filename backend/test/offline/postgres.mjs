// Base exclusivamente local y temporal. Ejecutar después de npm run build.
import 'reflect-metadata';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { Client } from 'pg';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient } from '../../dist/generated/prisma/client.js';
import { ConfigService } from '@nestjs/config';
import { PresentialSaleService } from '../../dist/modules/sales-billing/use-cases/CU27-registrar-venta-presencial/presential-sale.service.js';
import { OfflineController } from '../../dist/modules/sales-billing/use-cases/CU27-registrar-venta-presencial/offline.controller.js';

const base = new URL(process.env.OFFLINE_TEST_DATABASE_URL || 'postgresql://offline_test:offline_test_local_only@127.0.0.1:55439/offline_test');
if (!['127.0.0.1', 'localhost'].includes(base.hostname) || !base.pathname.startsWith('/offline_test')) throw new Error('Solo se admiten bases locales de prueba offline_test');
const admin = new Client({ connectionString: base.toString() });
await admin.connect();
const name = `offline_test_${Date.now()}`;
await admin.query(`CREATE DATABASE "${name}"`);
base.pathname = `/${name}`;
const sql = new Client({ connectionString: base.toString() });
const prisma = new PrismaClient({ adapter: new PrismaPg({ connectionString: base.toString() }) });
try {
  await sql.connect();
  await sql.query(await readFile(new URL('../../Base de Datos/Dressly_DB.sql', import.meta.url), 'utf8'));
  const migration = await readFile(new URL('../../prisma/offline-schema.sql', import.meta.url), 'utf8');
  await sql.query(migration); await sql.query(migration);
  const pos = new PresentialSaleService(prisma, { logAction: async () => {} }, new ConfigService({}));
  const controller = new OfflineController(prisma, pos);
  const cashier = { user: { id_usuario: 8, id_rol: 4, rol: 'Cajero' } };
  const manager = { user: { id_usuario: 6, id_rol: 1, rol: 'Administrador' } };
  const preparation = await controller.prepare(cashier, { branch: 1, terminal: 'test-terminal-a', initialMinor: 1000 });
  await assert.rejects(() => controller.prepare(cashier, { branch: 1, terminal: 'test-terminal-b' }));
  const variant = preparation.products.flatMap(product => product.variantes).find(item => item.stock_disponible > 0);
  assert.ok(variant);
  const price = Math.round(variant.precio_final * 100);
  const body = { id: randomUUID(), preparationId: preparation.id, createdAt: new Date().toISOString(), receivedMinor: price, customer: { name: 'Cliente de prueba', ci: '12345', nit: '12345', businessName: 'Venta de prueba offline' }, items: [{ variant: variant.id_producto_variante, quantity: 1, priceMinor: price }] };
  const results = await Promise.all([controller.sync(cashier, body), controller.sync(cashier, body)]);
  assert.equal(results[0].status, 'CONFIRMED'); assert.equal(results[0].result.cliente.nit_ci, '12345'); assert.deepEqual(results[0], results[1]);
  assert.equal(await prisma.venta.count(), 1); assert.equal(await prisma.pago.count(), 1);
  const stock = await prisma.inventario_sucursal.findUnique({ where: { id_sucursal_id_producto_variante: { id_sucursal: 1, id_producto_variante: variant.id_producto_variante } } });
  assert.equal(stock.stock_disponible, variant.stock_disponible - 1);
  await assert.rejects(() => controller.sync(cashier, { ...body, receivedMinor: price + 1 }));
  await prisma.inventario_sucursal.update({ where: { id_inventario_sucursal: stock.id_inventario_sucursal }, data: { stock_disponible: 0 } });
  const conflicting = { ...body, id: randomUUID(), createdAt: new Date().toISOString() };
  assert.equal((await controller.sync(cashier, conflicting)).status, 'REVIEW');
  assert.equal(await prisma.venta.count(), 1); assert.equal(await prisma.pago.count(), 1);
  await assert.rejects(() => controller.closeCash(cashier, preparation.sessionId, { countedMinor: 1000 + price, operationIds: [body.id, conflicting.id] }));
  await assert.rejects(() => controller.resolve(cashier, conflicting.id, { note: 'Sin permiso administrativo' }));
  await prisma.inventario_sucursal.update({ where: { id_inventario_sucursal: stock.id_inventario_sucursal }, data: { stock_disponible: 1 } });
  const parent = preparation.products.find(product => product.variantes.some(item => item.id_producto_variante === variant.id_producto_variante));
  await prisma.producto.update({ where: { id_producto: parent.id_producto }, data: { precio_base: { increment: 5 } } });
  const approved = await controller.resolve(manager, conflicting.id, { note: 'Existencias verificadas y regularizadas para la venta cobrada' });
  assert.equal(approved.status, 'CONFIRMED');
  assert.equal(Math.round(approved.result.liquidacion.total * 100), price);
  const recovered = { ...body, id: randomUUID(), createdAt: new Date().toISOString() };
  await assert.rejects(() => controller.recover(cashier, { operation: recovered, note: 'Sin privilegios de administrador' }));
  assert.equal((await controller.recover(manager, { operation: recovered, note: 'Respaldo del cajero recuperado tras pérdida de acceso' })).status, 'REVIEW');
  await prisma.inventario_sucursal.update({ where: { id_inventario_sucursal: stock.id_inventario_sucursal }, data: { stock_disponible: 1 } });
  assert.equal((await controller.resolve(manager, recovered.id, { note: 'Cobro y stock de la venta recuperada verificados' })).status, 'CONFIRMED');
  assert.deepEqual(await controller.resolve(manager, conflicting.id, { note: 'Reintento de la resolución administrativa' }), approved);
  assert.equal(await prisma.venta.count(), 3); assert.equal(await prisma.pago.count(), 3);
  assert.equal((await prisma.$queryRaw`SELECT count(*)::integer AS total FROM offline_resolution`)[0].total, 3);
  await assert.rejects(() => controller.closeCash(cashier, preparation.sessionId, { countedMinor: 1000 + price * 2, operationIds: [body.id] }));
  const close = { countedMinor: 1000 + price * 3, operationIds: [body.id, conflicting.id, recovered.id] };
  await assert.rejects(() => controller.closeCash(manager, preparation.sessionId, close));
  const closed = await controller.closeCash(manager, preparation.sessionId, { ...close, note: 'Todos los tickets y el efectivo del turno recuperado verificados' });
  assert.equal(closed.expectedMinor, close.countedMinor); assert.equal(closed.differenceMinor, 0);
  assert.deepEqual(await controller.closeCash(cashier, preparation.sessionId, close), closed);
  await assert.rejects(() => controller.sync(cashier, { ...body, id: randomUUID() }));
  console.log('PASS PostgreSQL: migración repetible, exclusividad, concurrencia/idempotencia, rollback, conciliación auditada, manifiesto y cierre repetible');
} finally {
  await prisma.$disconnect(); await sql.end();
  await admin.query(`DROP DATABASE "${name}"`); await admin.end();
}
